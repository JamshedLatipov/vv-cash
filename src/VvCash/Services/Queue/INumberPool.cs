using System;
using System.Threading.Tasks;

namespace VvCash.Services.Queue;

public interface INumberPool
{
    /// <summary>Следующий номер для клиента, привязанный к заказу
    /// <paramref name="orderId"/>. Никого не спрашивает по сети — на этом стоит
    /// вся оффлайн-устойчивость очереди.
    ///
    /// orderId — не украшение параметра, а то, чем ReleaseAsync ниже отличает
    /// живой номер от чужого: пул запоминает, какому заказу он выдан, и позже
    /// освобождает номер только по предъявлении того же id (см. докстринг
    /// ReleaseAsync о том, какую ошибку это исправило).</summary>
    Task<int> IssueAsync(Guid orderId);

    /// <summary>Возвращает номер в оборот — но только если он всё ещё выдан
    /// ИМЕННО заказу <paramref name="orderId"/>. Раньше кулдауна он всё равно
    /// не выдастся — см. NumberPool.CooldownIssues.
    ///
    /// Проверка по orderId, не только по значению number, — критично, а не
    /// подстраховка: сервер называет закрытые заказы этой кассы на каждом
    /// опросе (см. QueueClient.FlushAsync) и ничего их оттуда не убирает, так
    /// что один и тот же заказ приходит сюда закрытым снова и снова, в том
    /// числе после того, как его номер уже переиздан кому-то новому. Гвард по
    /// одному только number — то, что было здесь раньше, — на такой стале-
    /// заявке освобождал бы чужой, живой номер; см. class docstring на
    /// NumberPool.ReleaseAsync за полным разбором.
    ///
    /// Повторный вызов с тем же orderId для уже свободного (или уже переизданного
    /// кому-то ещё) номера — no-op: он не отодвигает окно кулдауна заново и не
    /// трогает нового держателя.</summary>
    Task ReleaseAsync(int number, Guid orderId);
}
