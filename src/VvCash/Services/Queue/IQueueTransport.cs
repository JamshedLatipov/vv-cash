using System.Collections.Generic;
using System.Threading.Tasks;
using VvCash.Models;

namespace VvCash.Services.Queue;

/// <summary>Итог попытки отправить заказ серверу. Три состояния, а не bool: сеть,
/// которая может отпустить в любой момент, и сервер, который отказал по существу
/// прямо сейчас, требуют разного ответа от FlushAsync — недоступность
/// останавливает досылку буфера целиком (следующие всё равно не дойдут тем же
/// рейсом), осознанный отказ — нет (он касается только этого заказа и ничего не
/// говорит о соседях в очереди). Bool не различал их: с ним один упрямый заказ во
/// главе буфера блокировал бы все последующие навсегда, без счётчика попыток и
/// без выхода из ротации.
///
/// Та же задача, что OfflineStorageService.MarkDocumentRejectedAsync решает для
/// исходящих документов бэкенда — здесь используется тот же словарь, а не
/// изобретается второй.</summary>
public enum PostOrderResult
{
    /// <summary>Сервер принял заказ.</summary>
    Sent,

    /// <summary>Сервер ответил и отказал по существу — то же самое тело
    /// повторной отправкой не пройдёт. Строка уходит из ротации, а не
    /// удаляется, — как отклонённый документ в UnsyncedDocuments.</summary>
    Refused,

    /// <summary>Сервер не отвечает. Может смениться на «доступен» на следующей
    /// попытке, а остальные заказы того же рейса всё равно не дойдут — на этом
    /// FlushAsync останавливает досылку буфера.</summary>
    Unreachable
}

/// <summary>Разговор кассы-клиента с кассой-сервером. Отдельным интерфейсом,
/// чтобы поведение при недоступном сервере проверялось без сокета: отказ
/// соединения к закрытому порту loopback на этой машине занимает ~2.2 с и
/// превращает такие тесты в минутные.</summary>
public interface IQueueTransport
{
    /// <summary>См. <see cref="PostOrderResult"/> — недоступность сети не
    /// исключение: это штатное состояние, а не ошибка.</summary>
    Task<PostOrderResult> PostOrderAsync(QueueOrder order);

    /// <summary>Закрытые заказы этой кассы — чтобы вернуть их номера в пул.</summary>
    Task<IReadOnlyList<QueueOrder>> GetClosedAsync(int tillIndex);
}
