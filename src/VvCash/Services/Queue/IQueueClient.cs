using System.Threading.Tasks;
using VvCash.Models;

namespace VvCash.Services.Queue;

/// <summary>Постановка заказа кассой-клиентом. Fail-open: сервер лежит — номер
/// всё равно выдан, бумага всё равно вышла, заказ лёг в локальный буфер —
/// продажа не встаёт никогда, это решение спеки (см. QueueClientTest).</summary>
public interface IQueueClient
{
    /// <summary>Выдаёт номер, пишет заказ локально и пробует отправить его на
    /// сервер. Неудачная отправка не отменяет ни номер, ни заказ — именно в этом
    /// и есть fail-open: касса без сети должна пробить продажу так же, как
    /// касса с сетью. Тот же принцип распространяется и на сбой самой БД
    /// очереди (заперт или переполнен queue.db): он логируется и глотается, а
    /// не бросается наружу, — вызывающий (ProceedToPayAsync) зовёт это уже
    /// после того, как чек ушёл в печать, и бросить исключение здесь означало
    /// бы отчитаться кассиру об ошибке на продаже, которая на самом деле уже
    /// состоялась.
    ///
    /// Возвращает null только тогда, когда не удалось получить сам номер —
    /// тогда заказу действительно неоткуда взяться. Если номер получен, но
    /// запись в буфер не удалась, метод всё равно возвращает заказ: сгоревший
    /// номер безобиден, а несостоявшаяся продажа — нет.</summary>
    Task<QueueOrder?> EnqueueAsync(SaleReceiptData sale);

    /// <summary>Досылает буфер и возвращает номера закрытых заказов этой кассы
    /// в пул.</summary>
    Task FlushAsync();

    /// <summary>Сколько заказов ещё лежит в исходящем буфере этой кассы —
    /// поставлены, но не подтверждены сервером очереди. Отдельный счётчик от
    /// PosViewModel.UnsyncedDocumentsCount: то не дошло до бэкенда, это не
    /// дошло до соседней кассы — разные проблемы, которые чинят разные люди
    /// разными действиями, и один и тот же номер над обоими отправил бы
    /// кассира не туда.</summary>
    Task<int> PendingCountAsync();
}
